const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** Kleine letter voor categorienamen midden in een zin ("Boomhutten" → "boomhutten"). */
const lc = (s: string) => s.toLowerCase();

/** "a, b en c" */
const list = (items: string[]) =>
  items.length <= 1 ? items.join('') : `${items.slice(0, -1).join(', ')} en ${items[items.length - 1]}`;

/** Landnaam met lidwoord waar het Nederlands dat vraagt ("de Verenigde Staten", "het Verenigd Koninkrijk"). */
const withArticle = (c: string) => {
  if (/^(Verenigde |Malediven|Maldiven|Bahama|Seychellen|Filipijnen|Galápagos|Galapagos|Florida Keys|Kaapverdië|Canarische|Azoren)/.test(c)) return `de ${c}`;
  if (/^Verenigd Koninkrijk/.test(c)) return `het ${c}`;
  return c;
};

/** Eilanden zeggen "op": op de Malediven, op Bali, op Saint Lucia. */
const ISLANDS = /^(Malediven|Maldiven|Bahama|Seychellen|Filipijnen|Galápagos|Galapagos|Saint Lucia|Bali|Bora Bora|Tahiti|Santorini|Zanzibar|Sri Lanka|Mauritius|Hawaï|Hawaii|Borneo|Kreta|Sicilië|Sardinië|Mallorca|Ibiza|Tenerife|Lombok|Komodo|Fiji|Curaçao|Aruba|Bonaire|Kaapverdië|Canarische|Azoren|Madeira|Florida Keys)/;

/** "in Zweden", "in de Verenigde Staten", "op de Malediven". */
const inC = (c: string) => `${ISLANDS.test(c) ? 'op' : 'in'} ${withArticle(c)}`;

/** "$ 300" → "rond $ 300"; "Vanaf $ 300" → "vanaf $ 300". */
const about = (r: string) => (/^vanaf/i.test(r) ? lc(r) : `rond ${r}`);

