const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** País con artículo cuando el uso lo pide («el Reino Unido», «los Emiratos Árabes Unidos»). */
const ARTICLE: Record<string, string> = {
  'Reino Unido': 'el Reino Unido',
  'Emiratos Árabes Unidos': 'los Emiratos Árabes Unidos',
};
const pais = (c: string) => ARTICLE[c] ?? c;
const enPais = (c: string) => `en ${pais(c)}`;
const aPais = (c: string) => `a ${pais(c)}`.replace(/^a el /, 'al ');
const dePais = (c: string) => `de ${pais(c)}`.replace(/^de el /, 'del ');
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** Nombre de categoría en minúscula dentro de la frase. */
const lc = (s: string) => s.toLowerCase();
/** Categorías de género femenino del glosario («Cabañas en los árboles», «Habitaciones submarinas»). */
const fem = (cat: string) => /^(cabañas|habitaciones)\b/i.test(cat.trim());
const losLas = (cat: string) => (fem(cat) ? 'las' : 'los');
const todos = (cat: string) => (fem(cat) ? 'Todas las' : 'Todos los');
const mejores = (cat: string) => (fem(cat) ? 'Las mejores' : 'Los mejores');

/** Minúscula solo en la primera letra (conserva «US$», nombres propios, etc.). */
const lcFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
/** Lista natural: «a, b y c». */
const lista = (xs: string[]) => (xs.length <= 1 ? xs.join('') : `${xs.slice(0, -1).join(', ')} y ${xs[xs.length - 1]}`);
/** Quita «Desde» de un rango del tipo «Desde 200 US$». */
const sinDesde = (r: string) => r.replace(/^\s*desde\s+/i, '');

