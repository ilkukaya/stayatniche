const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** Preposition + article in front of a (localized) country name: in Svezia, negli Stati Uniti, alle Maldive… */
const IN_EXCEPTIONS: Record<string, string> = {
  'stati uniti': 'negli Stati Uniti',
  'emirati arabi uniti': 'negli Emirati Arabi Uniti',
  'paesi bassi': 'nei Paesi Bassi',
  'regno unito': 'nel Regno Unito',
  'maldive': 'alle Maldive',
  'bahamas': 'alle Bahamas',
  'seychelles': 'alle Seychelles',
  'filippine': 'nelle Filippine',
  'isole cook': 'alle Isole Cook',
  'isole fiji': 'alle Isole Fiji',
  'figi': 'alle Figi',
  'saint lucia': 'a Saint Lucia',
  'mauritius': 'a Mauritius',
  'cuba': 'a Cuba',
  'singapore': 'a Singapore',
  'hong kong': 'a Hong Kong',
  'più paesi': 'in più paesi',
};
const inCountry = (c: string) => {
  const name = c.trim();
  const head = name.split(/\s*[/(]/)[0].trim().toLowerCase();
  const exc = IN_EXCEPTIONS[head];
  return exc ? exc + name.slice(name.split(/\s*[/(]/)[0].trim().length) : `in ${name}`;
};
/** Same rule for URL slugs ("stati-uniti" → "negli-stati-uniti"). */
const inCountrySlug = (slug: string) => {
  const key = slug.replace(/-/g, ' ');
  const exc = IN_EXCEPTIONS[key];
  return exc ? exc.toLowerCase().replace(/\s+/g, '-') : `in-${slug}`;
};

/** Category names: lower-case first letter, gender, plural article. */
const lcFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const isFem = (cat: string) => /^(case|camere|bolle|capanne|cabine|ville|tende|suite)\b/i.test(cat.trim());
const artPl = (cat: string) => (isFem(cat) ? 'le' : /^(h|[aeiou]|s[^aeiou]|z|gn|ps|x|y)/i.test(cat.trim()) ? 'gli' : 'i');
const all = (cat: string) => `${isFem(cat) ? 'tutte' : 'tutti'} ${artPl(cat)} ${lcFirst(cat)}`;
const sulPl = (cat: string) => ({ le: 'sulle', gli: 'sugli', i: 'sui' } as Record<string, string>)[artPl(cat)];

