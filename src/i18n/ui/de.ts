const NBSP = ' ';
const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** Aufzählung mit „und“ vor dem letzten Glied. */
const joinAnd = (xs: string[]) => (xs.length < 2 ? xs.join('') : `${xs.slice(0, -1).join(', ')} und ${xs[xs.length - 1]}`);

/** "Ab 300 $" → "300 $" (für Sätze, die selbst schon „ab“/„bei“ enthalten). */
const bare = (s: string) => s.replace(/^\s*ab\s+/i, '');
/** "Ab 300 $" → "ab 300 $" (mitten im Satz). */
const lowerAb = (s: string) => s.replace(/^\s*Ab\b/, 'ab');
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

