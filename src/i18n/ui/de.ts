const placeForm = (c: string, i: 0 | 1 | 2, fallback: string) => {
  const name = c.trim();
  const base = name.split(/\s*(?:\(|\/|,)\s*/)[0].trim();
  const f = PLACES[base];
  return f ? f[i] + name.slice(base.length) : `${fallback}${name}`;
};
/** „in Schweden“, „in der Schweiz“, „auf den Malediven“ */
const inCountry = (c: string) => placeForm(c, 0, 'in ');
/** „nach Schweden“, „in die Schweiz“, „auf die Malediven“ */
const toCountry = (c: string) => placeForm(c, 1, 'nach ');
/** „für Schweden“, „für die Schweiz“, „für den Oman“ */
const forCountry = (c: string) => `für ${placeForm(c, 2, '')}`;

/**
 * Kategorienamen mitten im Satz. Kommen teils kleingeschrieben an („baumhaushotels“);
 * Substantive werden wieder großgeschrieben, das Adjektiv in „Schwimmende Hotels“ klein.
 */
const catMid = (cat: string) =>
  cat
    .trim()
    .split(/\s+/)
    .map((w) => (/^schwimmende$/i.test(w) ? 'schwimmende' : w.replace(/(^|-)(\p{L})/gu, (_m, p: string, ch: string) => p + ch.toUpperCase())))
    .join(' ');
/** Nach bestimmtem Artikel / „alle“ (schwache Beugung): „die besten schwimmenden Hotels“. */
const catWeak = (cat: string) => catMid(cat).replace(/^schwimmende /, 'schwimmenden ');
/** Am Satzanfang. */
const catStart = (cat: string) => cap(catMid(cat));

